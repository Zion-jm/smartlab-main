const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
require('dotenv').config();
const { PrismaClient } = require('@prisma/client');
async function main() {
  const url = new URL(process.env.TEST_DATABASE_URL || process.env.DATABASE_URL);
  assert(['localhost','127.0.0.1'].includes(url.hostname), 'Local PostgreSQL only');
  assert.notEqual(process.env.NODE_ENV, 'production');
  url.pathname = '/smartlab_test';
  const schema = 'smartlab_test_run_' + Date.now() + '_' + crypto.randomBytes(8).toString('hex');
  url.searchParams.set('schema', schema);
  process.env.DATABASE_URL = url.href;
  process.env.NODE_ENV = 'test';
  process.env.EMAIL_DELIVERY_ENABLED = 'false';
  const db = new PrismaClient({datasources:{db:{url:url.href}}});
  const { resolveRequestIntent } = require('../dist/services/requestTypePolicy');
  const { approveRequest } = require('../dist/services/approvalService');
  const { changeLoanStatus } = require('../dist/services/inventoryMovementService');
  const { inventoryTransaction } = require('../dist/services/inventoryTransaction');
  const { cancelBorrowRequest } = require('../dist/services/cancelBorrowRequestService');
  const { summarizeRequest, borrowRequestInclude } = require('../dist/services/borrowRequestService');
  try {
    await db.$connect();
    const migrate = spawnSync(process.execPath, [require.resolve('prisma/build/index.js'), 'migrate', 'deploy'], { env: process.env, encoding:'utf8', windowsHide:true });
    assert.equal(migrate.status, 0, 'Isolated migrations must apply successfully');
    const year = await db.academicYear.create({data:{year:'2035-2036',isActive:true}});
    const term = await db.term.create({data:{name:'Test semester',isActive:true}});
    const user = role => db.user.create({data:{email:role+'@test.invalid',passwordHash:'test-only',firstName:'Test',lastName:role,role}});
    const admin = await user('ADMIN'), faculty = await user('FACULTY'), student = await user('STUDENT');
    const profile = await db.facultyProfile.create({data:{userId:faculty.id}});
    const room = await db.room.create({data:{name:'ICT laboratory',isComputerLab:true}});
    const equipment = await db.equipment.create({data:{name:'Camera',totalQuantity:2,availableQuantity:2}});
    const dateNeeded = new Date('2035-06-12T00:00:00+08:00');
    const timeStart = new Date('2035-06-12T09:00:00+08:00'), timeEnd = new Date('2035-06-12T10:00:00+08:00');
    const body = {requestType:'EQUIPMENT',facultyId:profile.id,dateNeeded:dateNeeded.toISOString(),timeStart:timeStart.toISOString(),timeEnd:timeEnd.toISOString(),purpose:'Class',usageRoomId:room.id};
    const items=[{equipmentId:equipment.id,quantity:1}];
    await assert.rejects(resolveRequestIntent(db,body,'ADMIN',items),{statusCode:403});
    await assert.rejects(resolveRequestIntent(db,{...body,requestType:'LABORATORY',roomId:room.id},'ADMIN',[]),{statusCode:403});
    const intent = await resolveRequestIntent(db,body,'STUDENT',items);
    assert.equal(intent.roomId,null); assert.equal(intent.usageRoomId,room.id);
    await assert.rejects(resolveRequestIntent(db,{...body,requestType:'LABORATORY',roomId:room.id},'STUDENT',items),{statusCode:403});
    await assert.rejects(resolveRequestIntent(db,{...body,requestType:'LEGACY'},'STUDENT',items),{statusCode:400});
    await assert.rejects(resolveRequestIntent(db,body,'STUDENT',[]),{statusCode:400});
    await assert.rejects(resolveRequestIntent(db,{...body,usageRoomId:null},'FACULTY',items),{statusCode:400});
    await assert.rejects(resolveRequestIntent(db,{...body,roomId:room.id},'FACULTY',items),{statusCode:400});
    const labIntent = await resolveRequestIntent(db,{...body,requestType:'LABORATORY',roomId:room.id},'FACULTY',[]);
    const create = (intent,owner,lines=[]) => db.borrowRequest.create({data:{...intent,requestedBy:owner.id,facultyId:profile.id,dateNeeded,timeStart,timeEnd,purpose:'Test',academicYearId:year.id,termId:term.id,items:{create:lines}}});
    const approve = id => approveRequest(db,{id,actorId:admin.id,actorRole:'ADMIN'});
    const lab = await create(labIntent,faculty);
    await approve(lab.id);
    assert.equal(await db.labSchedule.count(),1);
    const loan = await create(intent,student,items);
    await approve(loan.id); // Same lab and time must not block equipment-only borrowing.
    assert.equal(await db.labSchedule.count(),1);
    const summary = summarizeRequest(await db.borrowRequest.findUniqueOrThrow({where:{id:loan.id},include:borrowRequestInclude}));
    assert.equal(summary.requestType,'EQUIPMENT'); assert.equal(summary.roomId,null); assert.match(summary.location,/ICT laboratory/);
    const conflictingLab = await create(labIntent,faculty);
    await assert.rejects(approve(conflictingLab.id),{statusCode:409});
    assert.equal((await db.borrowRequest.findUnique({where:{id:conflictingLab.id}})).status,'PENDING');
    await assert.rejects(inventoryTransaction(db,tx=>changeLoanStatus(tx,lab.id,'borrow')),{statusCode:400});
    await inventoryTransaction(db,tx=>changeLoanStatus(tx,loan.id,'borrow'));
    assert.equal((await db.equipment.findUnique({where:{id:equipment.id}})).availableQuantity,1);
    await inventoryTransaction(db,tx=>changeLoanStatus(tx,loan.id,'return'));
    assert.equal((await db.equipment.findUnique({where:{id:equipment.id}})).availableQuantity,2);
    await assert.rejects(inventoryTransaction(db,tx=>changeLoanStatus(tx,loan.id,'return')),{statusCode:409});
    await inventoryTransaction(db,tx=>cancelBorrowRequest(tx,{id:lab.id,actorId:admin.id,actorRole:'ADMIN'}));
    assert.equal(await db.labSchedule.count(),0);
    await approve(conflictingLab.id);
    const fullItems=[{equipmentId:equipment.id,quantity:2}];
    const a=await create(intent,student,fullItems), b=await create(intent,faculty,fullItems);
    const race=await Promise.allSettled([approve(a.id),approve(b.id)]);
    assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
    assert.equal(race.filter(r=>r.status==='rejected').length,1);
    const winner=race[0].status==='fulfilled'?a:b;
    await inventoryTransaction(db,tx=>cancelBorrowRequest(tx,{id:winner.id,actorId:admin.id,actorRole:'ADMIN'}));
    const legacy=await create({},student,[]);
    assert.equal(legacy.requestType,'LEGACY');
    assert.equal(legacy.usageRoomId,null);
    const legacyLab = await create({roomId:room.id},student);
    await assert.rejects(approve(legacyLab.id),{statusCode:403});
    assert.equal((await db.borrowRequest.findUnique({where:{id:legacyLab.id}})).status,'PENDING');
    await inventoryTransaction(db,tx=>cancelBorrowRequest(tx,{id:conflictingLab.id,actorId:admin.id,actorRole:'ADMIN'}));
    const combined = await create(labIntent,faculty,items);
    await approve(combined.id);
    assert.equal(await db.labSchedule.count({where:{borrowRequestId:combined.id}}),1);
    await inventoryTransaction(db,tx=>changeLoanStatus(tx,combined.id,'borrow'));
    await inventoryTransaction(db,tx=>cancelBorrowRequest(tx,{id:combined.id,actorId:admin.id,actorRole:'ADMIN'}));
    assert.equal(await db.labSchedule.count({where:{borrowRequestId:combined.id}}),0);
    assert.equal((await db.equipment.findUnique({where:{id:equipment.id}})).availableQuantity,2);
    const shortage = await create(labIntent,faculty,[{equipmentId:equipment.id,quantity:3}]);
    await assert.rejects(approve(shortage.id));
    assert.equal((await db.borrowRequest.findUnique({where:{id:shortage.id}})).status,'PENDING');
    assert.equal(await db.labSchedule.count({where:{borrowRequestId:shortage.id}}),0);
    assert(await db.auditLog.count()>0);
    console.log('PASS: migration, legacy defaults, student restrictions, required items/location, equipment-only lab usage, room conflicts, atomic approvals, release/return, double-return protection, cancellation, and competing equipment approvals.');
  } finally {
    await db.$executeRawUnsafe('DROP SCHEMA IF EXISTS "'+schema+'" CASCADE');
    await db.$disconnect();
  }
}
main().catch(error=>{ console.error('Request-type tests failed:',error.code || error.name, error instanceof assert.AssertionError ? error.message : 'Check local smartlab_test availability.'); process.exitCode=1; });
