// Isolated loopback database + real equipment HTTP routes. Never modifies public data.
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
require('dotenv').config();
async function main() {
  const { equipmentText, assertEquipmentVersion } = require('../dist/services/equipmentValidation');
  assert.equal(equipmentText('  HDMI   Cable ', 'Name', 150, true), 'HDMI Cable');
  for (const value of [23, {}, [], '', ' '.repeat(3), 'x'.repeat(151)]) assert.throws(() => equipmentText(value, 'Name', 150, true), {statusCode:400});
  assert.throws(() => equipmentText({}, 'Description', 1000), {statusCode:400});
  assert.throws(() => equipmentText('x'.repeat(1001), 'Description', 1000), {statusCode:400});
  const now = new Date();
  assertEquipmentVersion(now.toISOString(), now);
  for (const value of [null, 'bad', new Date(now.getTime()-1).toISOString()]) assert.throws(() => assertEquipmentVersion(value, now), {statusCode:409});
  console.log('PASS: text limits, input types, normalization and version checks.');
  const url = new URL(process.env.TEST_DATABASE_URL || process.env.DATABASE_URL);
  assert(['localhost','127.0.0.1'].includes(url.hostname), 'Local PostgreSQL only');
  assert.notEqual(process.env.NODE_ENV, 'production');
  url.pathname = '/smartlab_test';
  const schema = 'equipment_test_' + crypto.randomBytes(12).toString('hex');
  url.searchParams.set('schema', schema);
  process.env.DATABASE_URL = url.href;
  process.env.NODE_ENV = 'test';
  process.env.JWT_SECRET = crypto.randomBytes(32).toString('hex');
  process.env.EMAIL_DELIVERY_ENABLED = 'false';
  const { prisma: db } = require('../dist/db/prisma');
  let server, connected = false;
  try {
    await db.$connect(); connected=true;
    const migration = spawnSync(process.execPath, [require.resolve('prisma/build/index.js'), 'migrate', 'deploy'], {env:process.env, encoding:'utf8', windowsHide:true, timeout:60000});
    assert.equal(migration.status,0,'Isolated migrations must apply');
    const actor = await db.user.create({data:{email:'equipment@test.invalid',firstName:'Test',lastName:'Admin',passwordHash:'unused',role:'ADMIN'}});
    const jwt = require('jsonwebtoken');
    const token = jwt.sign({userId:actor.id,sessionVersion:actor.sessionVersion},process.env.JWT_SECRET);
    const app = require('express')(); app.use(require('express').json()); app.use('/equipment',require('../dist/routes/equipment').default);
    server = await new Promise(resolve => {const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
    const base='http://127.0.0.1:'+server.address().port+'/equipment';
    const call=async(method,path,body,status)=>{
      const r=await fetch(base+path,{method,headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
      const json=await r.json(); assert.equal(r.status,status,JSON.stringify(json)); return json;
    };
    let item=await call('POST','',{name:'  HDMI   Cable ',totalQuantity:5},201);
    assert.equal(item.name,'HDMI Cable');
    await call('POST','',{name:'hdmi cable'},409);
    await assert.rejects(db.equipment.create({data:{name:'HDMI  CABLE'}}),{code:'P2002'});
    for (const body of [{name:4},{name:'x'.repeat(151)},{name:'Bad',description:{}},{name:'Bad',totalQuantity:-1},{name:'Bad',totalQuantity:1.5},{name:'Bad',borrowedQuantity:1,totalQuantity:5}]) await call('POST','',body,400);
    const update=(body,status=200,version=item.updatedAt)=>call('PUT','/'+item.id,{...body,expectedUpdatedAt:version},status);
    await update({name:'Cable revised'},409,null);
    await update({totalQuantity:6},400);
    await update({totalQuantity:null,adjustmentReason:'Invalid value'},400);
    await update({totalQuantity:6,adjustmentReason:'x'.repeat(501)},400);
    const other=await call('POST','',{name:'Other equipment'},201);
    await update({name:other.name},409);
    item=await update({totalQuantity:6,adjustmentReason:'Received one unit'});
    const stale=item.updatedAt;
    item=await update({description:'Updated description'});
    await update({description:'stale edit'},409,stale);
    const race=await Promise.all([0,1].map(i=>fetch(base+'/'+item.id,{method:'PUT',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({name:'HDMI Cable',description:'Race '+i,expectedUpdatedAt:item.updatedAt})})));
    assert.deepEqual(race.map(r=>r.status).sort(),[200,409]);
    item=await db.equipment.findUnique({where:{id:item.id}}); item.updatedAt=item.updatedAt.toISOString();
    const duplicateRace=await Promise.all([0,1].map(()=>fetch(base,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({name:'Race equipment'})})));
    assert.deepEqual(duplicateRace.map(r=>r.status).sort(),[201,409]);
    const year=await db.academicYear.create({data:{year:'2035-2036',isActive:true}});
    const term=await db.term.create({data:{name:'First',isActive:true}});
    const request=await db.borrowRequest.create({data:{requestedBy:actor.id,requestType:'EQUIPMENT',usageLocation:'Test venue',academicYearId:year.id,termId:term.id,dateNeeded:new Date('2035-06-12'),timeStart:new Date('2035-06-12T01:00:00Z'),timeEnd:new Date('2035-06-12T02:00:00Z'),status:'APPROVED',items:{create:[{equipmentId:item.id,quantity:4}]}}});
    await update({totalQuantity:3,adjustmentReason:'Reduction'},409);
    assert.equal((await db.equipment.findUnique({where:{id:item.id}})).totalQuantity,6);
    await call('POST','/'+item.id+'/retire',{},409);
    const {inventoryTransaction}=require('../dist/services/inventoryTransaction');
    const {changeLoanStatus}=require('../dist/services/inventoryMovementService');
    await inventoryTransaction(db,tx=>changeLoanStatus(tx,request.id,'borrow'));
    await update({description:'Opened before checkout'},409);
    await call('POST','/'+item.id+'/retire',{},200);
    await call('POST','',{name:'hdmi cable'},409);
    await inventoryTransaction(db,tx=>changeLoanStatus(tx,request.id,'return'));
    await assert.rejects(inventoryTransaction(db,tx=>changeLoanStatus(tx,request.id,'return')),{statusCode:409});
    await call('POST','/'+item.id+'/restore',{},200);
    const fresh=await db.equipment.findUnique({where:{id:item.id}});
    assert.equal(fresh.availableQuantity,6); assert.equal(fresh.borrowedQuantity,0);
    assert.equal(await db.borrowRequestItem.count({where:{equipmentId:item.id}}),1);
    const audit=await db.auditLog.findMany({where:{entityId:item.id,action:'UPDATE'}});
    assert(audit.some(a=>a.details.adjustmentReason==='Received one unit'));
    console.log('PASS: HTTP validation, duplicate names, migration, concurrent creates/edits, stale edits, reasons/audits, reservation rollback, checkout, archive, return, restore and preserved history.');
  } finally {
    if(server)await new Promise(resolve=>server.close(resolve));
    if(connected)await db.$executeRawUnsafe('DROP SCHEMA IF EXISTS "'+schema+'" CASCADE');
    await db.$disconnect();
  }
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
